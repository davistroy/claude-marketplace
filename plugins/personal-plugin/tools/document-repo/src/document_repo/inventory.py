"""List every file in a target repo and decide which ones the skill documents.

The output ("the inventory") is the first input to the whole run. It says, per
file: its language, its size, and either ``skip: None`` (document it) or the
reason to leave it alone. It also lists dependency manifests and likely entry
points, so the analysis agents know where execution starts.

Files are listed with ``git ls-files`` so .gitignore is honoured. A directory
that is not a git repo falls back to a plain directory walk.
"""

from __future__ import annotations

import json
import os
import re
import subprocess
from collections.abc import Iterator
from pathlib import Path, PurePosixPath
from typing import Any

from .languages import detect

try:  # Python 3.11+
    import tomllib
except ModuleNotFoundError:  # pragma: no cover - Python 3.10 has no tomllib
    tomllib = None  # type: ignore[assignment]

SKIP_REASONS = frozenset(
    {
        "symlink",
        "skipped-dir",
        "lock-file",
        "minified",
        "migration",
        "binary",
        "no-comment-syntax",
        "generated",
    }
)
SKIP_DIRS = frozenset(
    {
        ".git",
        "node_modules",
        ".venv",
        "venv",
        "__pycache__",
        "dist",
        "build",
        "coverage",
        ".next",
        ".nuxt",
        ".turbo",
        ".cache",
        "vendor",
        "third_party",
        ".mypy_cache",
        ".pytest_cache",
        ".tox",
        "target",
        ".document-repo",
    }
)
#: The skill's own output directory, skipped only at the repo root.
OUTPUT_DIR = "explorer"
LOCK_FILES = frozenset(
    {
        "package-lock.json",
        "pnpm-lock.yaml",
        "yarn.lock",
        "poetry.lock",
        "Pipfile.lock",
        "uv.lock",
        "Cargo.lock",
        "go.sum",
        "composer.lock",
        "Gemfile.lock",
    }
)
MINIFIED_SUFFIXES = (".min.js", ".min.css", ".map")
GENERATED_MARKERS = (
    "@generated",
    "do not edit",
    "auto-generated",
    "autogenerated",
    "code generated",
)
MANIFESTS = frozenset(
    {
        "package.json",
        "pyproject.toml",
        "setup.py",
        "setup.cfg",
        "requirements.txt",
        "go.mod",
        "Cargo.toml",
        "pom.xml",
        "build.gradle",
        "Gemfile",
        "composer.json",
    }
)
COMPOSE_FILES = frozenset(
    {"docker-compose.yml", "docker-compose.yaml", "compose.yml", "compose.yaml"}
)
ENTRY_NAMES = frozenset(
    {
        "main.py",
        "__main__.py",
        "app.py",
        "manage.py",
        "server.py",
        "cli.py",
        "wsgi.py",
        "asgi.py",
        "index.ts",
        "index.js",
        "main.ts",
        "main.js",
        "server.ts",
        "server.js",
        "app.ts",
        "app.js",
        "main.go",
    }
)
#: SQL migrations are never commented (SEC-03). Migration tools checksum the files they have
#: applied, so a header comment makes Flyway refuse to migrate, Prisma offer a database reset and
#: sqlx refuse to run. A ``.sql`` file is one when a directory above it is named here (sqlx,
#: golang-migrate, Prisma's ``migrations/<name>/migration.sql``) or its name is a Flyway
#: versioned, undo or repeatable migration (``V1__x.sql``, ``U1__x.sql``, ``R__x.sql``) anywhere.
MIGRATION_DIRS = frozenset({"migrations", "migration", "migrate"})
_FLYWAY_NAME = re.compile(r"(?:[VU]\d+(?:[._]\d+)*|R)__.*\.sql", re.IGNORECASE)
HEAD_BYTES = 8192
#: Largest single read count_lines makes, so memory stays flat however big the file is.
CHUNK_BYTES = 1 << 20


def _in_skipped_dir(parts: tuple[str, ...]) -> bool:
    """True when a path, split into components, sits under a directory the skill never documents.

    ``OUTPUT_DIR`` counts only as a directory at the repo root: a root *file* named
    ``explorer`` has a single component and is not skipped, and ``src/explorer/`` is ordinary
    source.
    """
    if len(parts) > 1 and parts[0] == OUTPUT_DIR:
        return True
    return any(part in SKIP_DIRS for part in parts[:-1])


def _walk(root: Path) -> Iterator[str]:
    for dirpath, dirnames, filenames in os.walk(root):
        dirnames[:] = [d for d in dirnames if d not in SKIP_DIRS]
        for name in filenames:
            path = Path(dirpath, name)
            # os.walk lists dangling symlinks (and sockets, FIFOs) as files; git mode filters them
            # the same way.
            if path.is_file():
                yield path.relative_to(root).as_posix()


def list_files(root: Path) -> list[str]:
    """Tracked plus untracked-but-not-ignored files, as sorted POSIX paths."""
    try:
        proc = subprocess.run(
            [
                "git",
                "-C",
                str(root),
                "ls-files",
                "-z",
                "--cached",
                "--others",
                "--exclude-standard",
            ],
            capture_output=True,
            check=True,
        )
    except (OSError, subprocess.CalledProcessError):
        return sorted(_walk(root))
    names = proc.stdout.decode("utf-8", "surrogateescape").split("\0")
    return sorted({n for n in names if n and (root / n).is_file()})


def _through_symlink(root: Path, parts: tuple[str, ...]) -> bool:
    """True when ``root / parts`` is a symlink or sits under one (``lstat`` of each component).

    A commenter's write follows a link (H-SYM): one leaving the repo edits a file git cannot
    restore, and one inside it gives two modules the same file, so parallel commenters race.
    """
    path = root
    for part in parts:
        path = path / part
        if path.is_symlink():
            return True
    return False


def skip_reason(root: Path, rel: str) -> str | None:
    """Return why ``rel`` must not be commented, or None when it should be.

    A symlink is decided first and nothing behind it is opened.
    """
    parts = PurePosixPath(rel).parts
    if _through_symlink(root, parts):
        return "symlink"
    if _in_skipped_dir(parts):
        return "skipped-dir"
    name = parts[-1]
    if name in LOCK_FILES or name.endswith(".lock"):
        return "lock-file"
    if name.endswith(MINIFIED_SUFFIXES):
        return "minified"
    if _is_migration(rel):
        return "migration"
    try:
        with (root / rel).open("rb") as fh:
            head = fh.read(HEAD_BYTES)
    except OSError:
        # Unreadable (vanished, permission denied): nothing can be commented, and "binary" is the
        # closest skip reason.
        return "binary"
    if b"\0" in head:
        return "binary"
    if detect(rel) is None:
        return "no-comment-syntax"
    first_lines = head.decode("utf-8", "replace").splitlines()[:5]
    if any(marker in line.lower() for line in first_lines for marker in GENERATED_MARKERS):
        return "generated"
    return None


def count_lines(path: Path) -> int:
    """Count lines by counting newline bytes in fixed-size chunks (memory ceiling rule).

    Iterating lines would buffer an entire line at once, which for a minified or
    single-line file is the whole file. A final line with no trailing newline still counts.
    """
    newlines = 0
    last = b""
    with path.open("rb") as fh:
        while chunk := fh.read(CHUNK_BYTES):
            newlines += chunk.count(b"\n")
            last = chunk[-1:]
    return newlines + (1 if last and last != b"\n" else 0)


def _is_migration(rel: str) -> bool:
    """True for a SQL migration file; see ``MIGRATION_DIRS``."""
    p = PurePosixPath(rel)
    if p.suffix.lower() != ".sql":
        return False
    return bool(_FLYWAY_NAME.fullmatch(p.name)) or any(
        part.lower() in MIGRATION_DIRS for part in p.parts[:-1]
    )


def _package_json_entries(root: Path, rel: str) -> list[dict[str, str]]:
    try:
        data = json.loads((root / rel).read_text(encoding="utf-8"))
    except (OSError, ValueError):
        return []
    if not isinstance(data, dict):
        return []
    out: list[dict[str, str]] = []
    if isinstance(data.get("main"), str):
        out.append({"path": rel, "why": f"package main -> {data['main']}"})
    bin_field = data.get("bin")
    if isinstance(bin_field, str):
        out.append({"path": rel, "why": f"package bin -> {bin_field}"})
    elif isinstance(bin_field, dict):
        for name, target in sorted(bin_field.items()):
            out.append({"path": rel, "why": f"package bin {name} -> {target}"})
    scripts = data.get("scripts")
    if not isinstance(scripts, dict):
        scripts = {}
    for key in ("start", "dev", "serve"):
        if key in scripts:
            out.append({"path": rel, "why": f"npm script {key} -> {scripts[key]}"})
    return out


def _pyproject_entries(root: Path, rel: str) -> list[dict[str, str]]:
    if tomllib is None:  # Python 3.10: no TOML reader, so no console scripts
        return []
    try:
        data = tomllib.loads((root / rel).read_text(encoding="utf-8"))
    except (OSError, ValueError):
        return []
    project = data.get("project")
    scripts = project.get("scripts") if isinstance(project, dict) else None
    if not isinstance(scripts, dict):
        return []
    return [
        {"path": rel, "why": f"console script {name} -> {target}"}
        for name, target in sorted(scripts.items())
    ]


def entry_candidates(root: Path, files: list[str]) -> list[dict[str, str]]:
    """Places where execution likely starts. Hints for analysts, not facts."""
    out: list[dict[str, str]] = []
    for rel in files:
        p = PurePosixPath(rel)
        if _in_skipped_dir(p.parts):
            continue
        if p.name in ENTRY_NAMES and len(p.parts) <= 4:
            out.append({"path": rel, "why": "conventional entry-point name"})
        if p.name == "package.json":
            out.extend(_package_json_entries(root, rel))
        if p.name == "pyproject.toml":
            out.extend(_pyproject_entries(root, rel))
        if p.name.startswith(("Dockerfile", "Containerfile")) or p.name in COMPOSE_FILES:
            out.append({"path": rel, "why": "container definition"})
    return out


def build_inventory(root: Path) -> dict[str, Any]:
    """Describe every file under ``root``. See the module docstring.

    Raises ``NotADirectoryError`` when ``root`` is not a directory, rather than
    reporting an empty repo for a mistyped path.
    """
    root = root.resolve()
    if not root.is_dir():
        raise NotADirectoryError(f"not a directory: {root}")
    rels = list_files(root)
    files: list[dict[str, Any]] = []
    by_lang: dict[str, int] = {}
    for rel in rels:
        reason = skip_reason(root, rel)
        lang = detect(rel)
        unread = reason in ("binary", "symlink")
        files.append(
            {
                "path": rel,
                "lang": lang.name if lang else None,
                "lines": 0 if unread else count_lines(root / rel),
                "bytes": (root / rel).lstat().st_size,
                "skip": reason,
            }
        )
        if reason is None and lang is not None:
            by_lang[lang.name] = by_lang.get(lang.name, 0) + 1
    return {
        "root": str(root),
        "files": files,
        "manifests": [
            r
            for r in rels
            if PurePosixPath(r).name in MANIFESTS and not _in_skipped_dir(PurePosixPath(r).parts)
        ],
        "entry_candidates": entry_candidates(root, rels),
        "summary": {
            "total_files": len(files),
            "source_files": sum(by_lang.values()),
            "by_lang": dict(sorted(by_lang.items())),
        },
    }
